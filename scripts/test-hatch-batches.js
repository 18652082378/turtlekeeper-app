const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const batches = require('../assets/turtle-batches');
const accounting = require('../assets/loss-accounting');
const source = fs.readFileSync(path.join(__dirname, '../app.js'), 'utf8');
const ctx = { crypto, speciesPhoto: () => 'shared-photo.jpg', formatDate: () => '2026-09-13' };
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('function buildBreedingHatchPlan('), source.indexOf('function confirmBreedingHatch(')), ctx);
const nest = { id: 'nest-1', date: '2026-09-09', motherName: '种母', poolId: 'p1', eggCount: 5 };
const species = { code: 'GHG', name: '果核蛋龟' };
const first = ctx.buildBreedingHatchPlan(nest, 3, species, [], [], '2026-09-11', 'event-1');
assert.equal(first.added.length, 3);
assert.equal(batches.group(first.added).length, 1);
assert.equal(batches.summary(first.added).count, 3);
assert.equal(batches.poolCount({ id: 'p1', count: 0 }, first.added), 3);
assert.equal(new Set(first.added.map(t => t.photo)).size, 1);
const savedNest = { ...nest, hatchArchiveIds: first.hatchArchiveIds, hatchEvents: first.hatchEvents, hatchCount: first.hatchCount };
assert.equal(ctx.buildBreedingHatchPlan(savedNest, 3, species, first.added, [], '2026-09-11', 'event-1').added.length, 0);
const more = ctx.buildBreedingHatchPlan(savedNest, 2, species, first.added, [], '2026-09-12', 'event-2');
const all = [...first.added, ...more.added];
assert.equal(more.hatchCount, 5);
assert.equal(batches.group(all).length, 2, 'Each confirmation creates its own batch');
assert.ok(first.added.every(t => t.acquiredDate === '2026-09-11'));
assert.ok(more.added.every(t => t.acquiredDate === '2026-09-12'));
const sameDay = ctx.buildBreedingHatchPlan(savedNest, 2, species, first.added, [], '2026-09-11', 'same-day-event');
assert.equal(batches.group([...first.added, ...sameDay.added]).length, 2, 'Separate records on the same date remain separate');
const other = ctx.buildBreedingHatchPlan({ ...nest, id: 'nest-2' }, 2, species, all, [], '2026-09-12');
assert.equal(batches.group([...all, ...other.added]).length, 3, 'Different nests remain separate');
const legacy = all.map(({ batchId, batchName, stage, ...t }) => t);
const original = JSON.stringify(legacy);
const normalized = batches.normalizeHatchBatches(legacy);
assert.equal(JSON.stringify(legacy), original, 'Legacy normalization does not mutate original archives');
assert.equal(batches.group(normalized).length, 2, 'Event IDs restore independent groups');
assert.deepEqual(batches.normalizeHatchBatches(normalized), normalized);
assert.equal(batches.members(normalized[0], normalized).length, 3);
const loss = { id: 'loss-1', type: 'loss', turtleId: normalized[0].id, recordDate: '2026-09-12' };
const lost = accounting.transferLoss({ turtles: normalized, ledgerRecords: [loss], memos: [] }, loss, normalized[0]);
assert.equal(batches.group(lost.turtles).length, 2);
assert.equal(batches.summary(lost.turtles).count, 4);
assert.equal(batches.summary(lost.turtles).lost, 1);
assert.equal(batches.poolCount({ id: 'p1', count: 0 }, lost.turtles), 4);
const completedNest = { ...nest, hatchArchiveIds: more.hatchArchiveIds, hatchCount: more.hatchCount, hatchEvents: more.hatchEvents };
assert.equal(ctx.buildBreedingHatchPlan(completedNest, 2, species, lost.turtles, lost.ledgerRecords, '2026-09-12', 'event-2').added.length, 0, 'Retry cannot recreate lost turtles');
assert.throws(() => ctx.buildBreedingHatchPlan(completedNest, 1, species, lost.turtles, lost.ledgerRecords, '2026-09-13'), /合计不能超过/);
assert.throws(() => ctx.buildBreedingHatchPlan({ ...nest, hatchCount: 5 }, 1, species, [], [], '2026-09-13'), /合计不能超过/, 'Old recorded hatch counts still use egg capacity');
for (const date of ['', '2026-02-30', '2026-09-08', '2026-09-14']) assert.throws(() => ctx.buildBreedingHatchPlan(nest, 1, species, [], [], date), /孵化日期/);
for (const count of [0, -1, 1.5]) assert.throws(() => ctx.buildBreedingHatchPlan(nest, count, species, [], [], '2026-09-11'), /整数/);
assert.equal(batches.group(ctx.buildBreedingHatchPlan({ ...nest, eggCount: 500 }, 500, species, [], [], '2026-09-11').added).length, 1);
console.log('Hatch events passed: 3+2 creates two rows, dates, same-day events, retry, legacy capacity, losses and egg limit.');
