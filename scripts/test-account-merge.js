const assert = require('node:assert/strict');
const { merge } = require('../assets/account-merge');
const accounting = require('../assets/loss-accounting');
const copy = x => JSON.parse(JSON.stringify(x));
const base = { accountName: 'test', accountAvatar: '', data: {
  turtles: ['a', 'b'].map(id => ({ id, code: id, price: 100, status: '正常饲养', photo: 'photo', measureHistory: [] })),
  ledgerRecords: ['a', 'b'].map(id => ({ id: 'buy-' + id, turtleId: id, type: 'purchase', amount: 100 })),
  memos: [], breedingRecords: [], turtlePools: [], activityLogs: [], keptSpecies: ['GHG'] } };
const loss = (s, id) => {
  const turtle = s.data.turtles.find(t => t.id === id), record = { id: 'loss-' + id, type: 'loss', turtleId: id, recordDate: '2026-09-11' };
  s.data.ledgerRecords.unshift(record); s.data = accounting.transferLoss(s.data, record, turtle);
};
let a = copy(base), b = copy(base);
loss(a, 'a'); loss(b, 'b');
let result = merge(base, a, b);
assert.equal(result.ready, true);
assert.equal(result.snapshot.data.turtles.filter(t => t.status === '已死亡').length, 2);
assert.equal(result.snapshot.data.ledgerRecords.length, 2);
assert.equal(result.snapshot.data.ledgerRecords.reduce((s, r) => s + r.amount, 0), 200);
assert.deepEqual(accounting.reconcile(result.snapshot.data), result.snapshot.data, 'merging must not transfer costs twice');
a = copy(base); b = copy(base);
a.data.turtles = a.data.turtles.filter(t => t.id !== 'a');
a.data.ledgerRecords.push({ id: 'sale-a', turtleId: 'a', type: 'sold', amount: 180 });
loss(b, 'b');
result = merge(base, a, b);
assert.equal(result.ready, true); assert.equal(result.snapshot.data.turtles.length, 1);
assert.ok(result.snapshot.data.ledgerRecords.some(r => r.id === 'sale-a'));
assert.ok(result.snapshot.data.ledgerRecords.some(r => r.id === 'loss-b'));
a = copy(base); b = copy(base);
a.data.turtles[0].weight = 30; b.data.turtles[0].weight = 40;
result = merge(base, a, b); assert.equal(result.ready, false);
result = merge(base, a, b, { [result.conflicts[0].key]: 'remote' });
assert.equal(result.ready, true); assert.equal(result.snapshot.data.turtles.find(t => t.id === 'a').weight, 40);
a.data.turtles[0].measureHistory = [{ id: 'local-growth', weight: 30 }];
b.data.turtles[0].measureHistory = [{ id: 'remote-growth', weight: 40 }];
result = merge(base, a, b);
result = merge(base, a, b, { [result.conflicts[0].key]: 'local' });
assert.deepEqual(new Set(result.snapshot.data.turtles.find(t => t.id === 'a').measureHistory.map(h => h.id)), new Set(['local-growth', 'remote-growth']), 'choosing current values cannot erase either growth history');
a = copy(base); b = copy(base);
a.data.turtles = a.data.turtles.filter(t => t.id !== 'a'); b.data.turtles[0].weight = 40;
assert.equal(merge(base, a, b).ready, false, 'delete versus update requires an explicit choice');
const poolBase = copy(base); poolBase.data.turtlePools = [{ id: 'pool', name: 'pool' }];
a = copy(poolBase); b = copy(poolBase); a.data.turtlePools = []; b.data.turtles[0].poolId = 'pool';
assert.equal(merge(poolBase, a, b).ready, false, 'do not create orphan pool assignments');
a = copy(base); b = copy(base);
a.data.turtles.push({ id: 'new-a', code: 'GHG-3' }); b.data.turtles.push({ id: 'new-b', code: 'GHG-3' });
assert.equal(merge(base, a, b).ready, false, 'offline duplicate codes must not silently enter the dashboard');
a = copy(base); b = copy(base);
a.data.keptSpecies.push('A'); b.data.keptSpecies.push('B');
assert.deepEqual(new Set(merge(base, a, b).snapshot.data.keptSpecies), new Set(['GHG', 'A', 'B']));
assert.equal(merge(null, a, b).ready, false, 'legacy snapshots cannot invent a common baseline');
const priceLocal = copy(base), priceRemote = copy(base);
priceLocal.data.turtles[0].price = 530; priceRemote.data.turtles[0].price = 540;
const priceConflict = merge(null, priceLocal, priceRemote).conflicts.find(c => c.label.startsWith('a'));
assert.ok(priceConflict.local.records.some(text => text.includes('530.00')), 'show local archive price before choosing a legacy conflict');
assert.ok(priceConflict.remote.records.some(text => text.includes('540.00')), 'show cloud archive price before choosing a legacy conflict');
assert.equal(merge(base, base, base).ready, true);
assert.deepEqual(merge(base, base, base).snapshot, base);
const hatch = copy(base); hatch.data.breedingRecords = [{ id: 'eggs', eggCount: 5, hatchCount: 0 }];
a = copy(hatch); b = copy(hatch);
a.data.breedingRecords[0].hatchCount = 3; b.data.breedingRecords[0].hatchCount = 4;
a.data.turtles.push({ id: 'hatch-a', code: 'hatch-a', sourceBreedingId: 'eggs' });
b.data.turtles.push({ id: 'hatch-b', code: 'hatch-b', sourceBreedingId: 'eggs' });
result = merge(hatch, a, b); assert.equal(result.ready, false, 'hatch totals cannot be blindly added beyond the clutch size');
result = merge(hatch, a, b, { [result.conflicts[0].key]: 'local' });
assert.equal(result.snapshot.data.breedingRecords[0].hatchCount, 3);
assert.ok(!result.snapshot.data.turtles.some(t => t.id === 'hatch-b'), 'choices preserve hatch totals and associated archives as one group');
const large = copy(base); large.data.turtles = Array.from({ length: 10000 }, (_, i) => ({ id: `t${i}`, code: `T${i}`, batchId: 'large' }));
const before = Date.now(); assert.equal(merge(large, large, large).ready, true);
assert.ok(Date.now() - before < 5000, 'batch merge must stay linear in archive count');
console.log('Account merge passed: independent sales/losses, exact costs, deletes, true conflicts, pool references, duplicate codes, clutch limits, legacy protection and 10000-member batches.');
