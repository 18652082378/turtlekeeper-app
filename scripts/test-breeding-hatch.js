const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const app = fs.readFileSync('app.js', 'utf8');
const ctx = { crypto, speciesPhoto: () => '/assets/placeholder.svg' };
vm.createContext(ctx);
vm.runInContext(app.slice(app.indexOf('function buildBreedingHatchPlan('), app.indexOf('function confirmBreedingHatch(')), ctx);
const species = { code: 'TEST', name: '测试龟' };
const record = { id: 'clutch', eggCount: 5, motherName: '种母', date: '2026-09-09' };
const first = ctx.buildBreedingHatchPlan(record, 2, species, [], [], '2026-09-09');
assert.equal(first.added.length, 2);
assert.equal(new Set(first.added.map(t => t.id)).size, 2);
assert.ok(first.added.every(t => t.sourceBreedingId === record.id && t.source === '孵化'));
const saved = { ...record, hatchArchiveIds: first.hatchArchiveIds };
assert.equal(ctx.buildBreedingHatchPlan(saved, 2, species, [], [], '2026-09-09').added.length, 0);
const more = ctx.buildBreedingHatchPlan(saved, 3, species, [first.added[0]], [{ turtleSnapshot: first.added[1] }], '2026-09-09');
assert.equal(more.added.length, 1);
assert.equal(more.hatchArchiveIds.length, 3);
for (const count of [0, -1, 1.5, NaN, Infinity, 6]) assert.throws(() => ctx.buildBreedingHatchPlan(record, count, species, [], [], '2026-09-09'));
assert.throws(() => ctx.buildBreedingHatchPlan(saved, 1, species, [], [], '2026-09-09'));
assert.throws(() => ctx.buildBreedingHatchPlan(record, 2, null, [], [], '2026-09-09'));
ctx.state = { loggedInPhone: 'user', ledgerDraftType: 'sold', ledgerDraftTurtleId: '', ledgerDraftPhoto: 'sale-photo', turtles: first.added, turtleFilter: 'old', turtlePoolFilter: 'old-pool', turtleSort: 'weight' };
ctx.ledgerDashboardPicker = null;
ctx.captureLedgerFormDraft = () => ({ turtleId: '__dashboard__', amount: '250', note: '保留备注' });
ctx.ledgerFormDraft = () => ctx.state.ledgerDraftForm;
ctx.setState = patch => Object.assign(ctx.state, patch);
ctx.toast = text => { throw Error(text); };
vm.runInContext(app.slice(app.indexOf('function startLedgerDashboardSelection('), app.indexOf('function readImageAsDataUrl(')), ctx);
ctx.startLedgerDashboardSelection();
assert.equal(ctx.state.page, 'home');
assert.equal(ctx.state.ledgerDraftForm.turtleId, '');
ctx.finishLedgerDashboardSelection(first.added[0].id);
assert.equal(ctx.state.page, 'ledger');
assert.equal(ctx.state.ledgerDraftForm.amount, '250');
assert.equal(ctx.state.ledgerDraftForm.note, '保留备注');
assert.equal(ctx.state.ledgerDraftTurtleId, first.added[0].id);
assert.equal(ctx.state.ledgerDraftPhoto, 'sale-photo');
assert.equal(ctx.state.turtleFilter, 'old');
ctx.startLedgerDashboardSelection();
ctx.finishLedgerDashboardSelection();
assert.equal(ctx.state.ledgerDraftTurtleId, first.added[0].id);
assert.equal(ctx.ledgerDashboardPicker, null);
console.log('Breeding and sale archive regression passed: create, repeat, increase, sold archive, invalid input, select, cancel, preserve draft.');
