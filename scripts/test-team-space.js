const assert = require('assert/strict');
const { fixture, month } = require('./team-test-fixture');
const { createTeamService, report, csv, recordAccountChange } = require('../server/team-space');
const { selectEntitlement, createApplePurchases } = require('../server/apple-team-purchases');
process.env.TURTLE_TEAM_TEST = '1';
async function main() {
  let db = fixture(), writes = 0;
  const service = createTeamService({ read: () => db, write: async () => { writes++; }, authenticate: (db, phone, token) => token === 'token' ? db.users[phone] : null,
    normalize: data => data });
  const req = (action, extra = {}, who = 1) => service.action({ action, phone: `1390000000${who}`, token: 'token', teamId: 'fixture-team', month, ...extra });
  const edit = async (action, extra, who = 1) => req(action, { revision: (await req('get', {}, who)).team.revision, ...extra }, who);
  await assert.rejects(req('get', {}, 4), e => e.status === 403);
  await assert.rejects(service.action({ action: 'list', phone: '13900000001', token: 'fake' }), e => e.status === 401);
  const restricted = (await req('get', {}, 3)).team;
  assert.equal(restricted.ledger.length, 0); assert.equal(restricted.report, null);
  assert(!JSON.stringify(restricted).includes('PRIVATE')); assert(!Object.hasOwn(restricted.turtles[0], 'price'));
  await assert.rejects(edit('turtle', { id: 't1', health: '观察' }, 3), e => e.status === 403);
  await assert.rejects(req('export', { kind: 'ledger' }, 2), e => e.status === 403);
  const stale = (await req('get')).team.revision;
  await edit('turtle', { id: 't1', health: '观察' }, 2);
  await assert.rejects(req('turtle', { id: 't1', health: '健康', revision: stale }), e => e.status === 409);
  await edit('turtle', { id: 't1', health: '健康', weight: '640', carapaceLength: '15.5' }, 2);
  assert.equal(db.users['13900000001'].data.turtles[0].measureHistory[0].newSnapshot.weight, 640);
  assert.equal((await req('share', { id: 't1', growth: true })).card.turtle.growth.at(-1).weight, 640);
  await edit('settings', { name: '青禾龟场', brandName: '青禾', contact: '联系龟场', logo: '', approvalRequired: true });
  const before = JSON.stringify(db.users['13900000001'].data);
  await edit('ledger', { type: 'sold', turtleId: 't1', amount: '2800', recordDate: `${month}-10` }, 2);
  assert.equal(JSON.stringify(db.users['13900000001'].data), before, 'pending approval must not change ledger or inventory');
  let team = (await req('get')).team, pending = team.approvals[0];
  await edit('approval', { id: pending.id, approve: true });
  assert(!db.users['13900000001'].data.turtles.some(t => t.id === 't1'));
  await assert.rejects(edit('approval', { id: pending.id, approve: true }), e => e.status === 409);
  await edit('ledger', { type: 'loss', turtleId: 't2', recordDate: `${month}-10` }, 2);
  pending = (await req('get')).team.approvals.find(p => p.status === 'pending');
  await edit('approval', { id: pending.id, approve: true });
  const r = report(db.users['13900000001'].data, month);
  assert.equal(r.purchase, 3250, 'loss transfer must preserve original cash purchase total');
  assert.equal(r.loss, 850); assert.equal(r.balance, 9790);
  const card = await req('share', { id: 't3', growth: true, breeding: true });
  assert(!JSON.stringify(card).includes('PRIVATE')); assert(!Object.hasOwn(card.card.turtle, 'price'));
  assert(csv([['=HYPERLINK("x")', '+2', '-10', '@x']]).includes("'=HYPERLINK"));
  await assert.rejects(edit('task', { id: 'task2' }, 2), e => e.status === 403);
  await edit('task', { id: 'task1' }, 2); assert.equal(db.users['13900000001'].teamSpace.tasks[0].done, true);
  for (let i = 4; i <= 7; i++) await edit('invite', { memberPhone: `1390000000${i}`, permissions: { ledger: 'read' } });
  await assert.rejects(edit('invite', { memberPhone: '13900000008' }), /最多 6/);
  const invitation = (await req('list', {}, 4)).invitations[0];
  await assert.rejects(req('accept', { id: invitation.id }, 5), e => e.status === 404);
  await req('accept', { id: invitation.id }, 4);
  assert.equal((await req('get', {}, 4)).team.permissions.ledger, 'read');
  await edit('member', { id: 'member-2', remove: true });
  await assert.rejects(req('get', {}, 2), e => e.status === 403);
  const owner = db.users['13900000001']; owner.teamEntitlement.expiresAt = '2020-01-01';
  owner.data.subscriptionPlan = 'pro';
  assert.equal((await req('get')).team.active, false);
  await assert.rejects(edit('task', { title: 'should deny', due: `${month}-10`, assignee: 'owner' }), e => e.status === 403);
  assert.equal((await req('get', {}, 3)).team.turtles.length, 0, 'expiry must hide shared records');
  const changed = structuredClone(owner.data); changed.turtles.pop(); recordAccountChange(owner, owner.data, changed);
  assert(owner.teamSpace.logs[0].summary.includes('删除 1')); assert(!Object.hasOwn(owner.teamSpace.logs[0], 'snapshot'));
  const now = Date.now(), token = '11111111-1111-4111-8111-111111111111';
  const tx = { bundleId: 'com.turtlekeeper.app', productId: 'keyoushouzhang.team.monthly', appAccountToken: token,
    transactionId: '123', originalTransactionId: '100', environment: 'Production', expiresDate: now + 100000 };
  assert.equal(selectEntitlement([{ status: 1, transaction: tx }], token).revoked, false);
  assert.equal(selectEntitlement([{ status: 5, transaction: tx }], token).revoked, true);
  assert.throws(() => selectEntitlement([{ status: 1, transaction: tx }], 'someone-else'), /其他/);
  assert.equal(Date.parse(selectEntitlement([{ status: 4, transaction: tx, renewal: { gracePeriodExpiresDate: now + 900000 } }], token).expiresAt), now + 900000);
  owner.appleAppAccountToken = token;
  const payment = createApplePurchases({ read: () => db, write: async () => {}, authenticate: (db, phone) => db.users[phone], query: async () => [{ status: 1, transaction: tx }] });
  const pay = () => payment.action({ action: 'verify', phone: owner.phone, transactionId: '123', environment: 'Production' });
  await pay(); await pay(); assert.equal(owner.teamEntitlement.originalTransactionId, '100', 'retries must not duplicate/extend membership');
  tx.environment = 'Sandbox';
  delete process.env.APPLE_IAP_SANDBOX_PHONES;
  await assert.rejects(pay(), e => e.status === 403);
  process.env.APPLE_IAP_SANDBOX_PHONES = owner.phone;
  await pay(); assert.equal(owner.teamEntitlement.environment, 'Sandbox');
  tx.revocationDate = Date.now(); await pay(); assert.equal(owner.teamEntitlement.revoked, true);
  delete process.env.APPLE_IAP_SANDBOX_PHONES;
  // Team metadata, nested arrays and purchases survive record-store reloads.
  const storage = require('../server/mysql-record-store'), { Driver } = require('./mysql-record-test-driver');
  const driver = new Driver(db); await storage.migrate(driver, db);
  const store = await storage.MysqlRecordStore.open(driver);
  store.data.users[owner.phone].teamSpace.branding.name = '持久化测试'; await store.write();
  const persisted = (await storage.load(driver)).database.users[owner.phone];
  assert.equal(persisted.teamSpace.branding.name, '持久化测试');
  assert.equal(persisted.teamSpace.members.length, owner.teamSpace.members.length);
  assert.equal(persisted.appleAppAccountToken, token);
  assert.deepEqual(persisted.teamEntitlement, owner.teamEntitlement);
  await store.close();
  console.log(`PASS: team authorization, isolation, invitations, approval, conflicts, financial accuracy, exports, expiry and Apple binding (${writes} durable writes)`);
}
main().catch(e => { console.error(e); process.exitCode = 1; });
