const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createLegacyData } = require('./legacy-upgrade-fixture');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', async route => {
      const url = new URL(route.request().url());
      if (url.hostname !== 'upgrade.test') return route.abort();
      if (url.pathname === '/config.js') return route.fulfill({ contentType: 'text/javascript', body: 'window.TURTLE_API_BASE_URL = "";' });
      const file = path.resolve(root, '.' + (url.pathname === '/' ? '/index.html' : decodeURIComponent(url.pathname)));
      if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) return route.fulfill({ status: 404, body: '' });
      const mime = { '.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html', '.jpg': 'image/jpeg', '.png': 'image/png', '.svg': 'image/svg+xml' };
      return route.fulfill({ body: fs.readFileSync(file), contentType: mime[path.extname(file)] || 'application/octet-stream' });
    });
    await page.addInitScript(data => {
      if (localStorage.getItem('turtlekeeper-state-v1')) return;
      localStorage.setItem('turtlekeeper-state-v1', JSON.stringify({ loggedInPhone: 'preview', registeredUsers: [{ phone: 'preview', accountName: '旧版升级测试', data }], policyConsentRequired: false }));
    }, createLegacyData(500, 1000.01));
    await page.goto('https://upgrade.test/', { waitUntil: 'load' });
    const skip = page.getByRole('button', { name: '跳过', exact: true });
    if (await skip.isVisible()) await skip.click();
    assert.equal(await page.evaluate(() => TurtleBatches.group(state.turtles).length), 3);
    assert.equal(await page.evaluate(() => TurtleBatches.summary(state.turtles.filter(t => t.source === '购买')).cost), 1000.01);
    assert.equal(await page.evaluate(() => state.turtles.length), 505);
    await page.evaluate(() => openLedgerForm('sold'));
    assert.equal(await page.locator('#ledgerForm option[data-batch-count="500"]').count(), 1, 'upgraded purchases remain collapsed in the ledger picker');
    await page.evaluate(() => setState({ page: 'breedingDetail', selectedBreedingId: 'legacy-count-only' }, { skipSave: true }));
    assert.equal(await page.locator('[name="hatchCount"]').count(), 0, 'removed cumulative input stays removed');
    assert.equal(await page.locator('[name="successfulHatchCount"]').inputValue(), '');
    await page.locator('[name="hatchSpeciesCode"]').selectOption('GHG');
    await page.locator('[name="hatchDate"]').fill('2026-09-10');
    await page.locator('#breedingHatchPanel').screenshot({ path: path.join(root, 'output', 'upgrade-historical-hatch.png') });
    await page.locator('[data-link-legacy-hatch]').click();
    assert.equal(await page.evaluate(() => state.breedingRecords.find(r => r.id === 'legacy-count-only').hatchCount), 3);
    assert.equal(await page.evaluate(() => state.turtles.filter(t => t.sourceBreedingId === 'legacy-count-only').length), 3);
    await page.evaluate(() => setState({ page: 'breedingDetail', selectedBreedingId: 'legacy-count-only' }, { skipSave: true }));
    assert.equal(await page.locator('[data-link-legacy-hatch]').count(), 0);
    await page.locator('[name="hatchSpeciesCode"]').selectOption('GHG');
    await page.locator('[name="hatchDate"]').fill('2026-09-11');
    await page.locator('[name="successfulHatchCount"]').fill('2');
    await page.locator('[data-confirm-breeding-hatch]').click();
    assert.equal(await page.evaluate(() => state.breedingRecords.find(r => r.id === 'legacy-count-only').hatchCount), 5);
    assert.equal(await page.evaluate(() => TurtleBatches.group(state.turtles.filter(t => t.sourceBreedingId === 'legacy-count-only')).length), 2);
    await page.reload({ waitUntil: 'load' });
    assert.equal(await page.evaluate(() => state.turtles.length), 510);
    assert.equal(await page.evaluate(() => TurtleBatches.poolCount(state.turtlePools[0], state.turtles)), 510);
    await page.evaluate(() => setState({ page: 'pools' }, { skipSave: true }));
    assert.match(await page.locator('.turtle-pool-row').innerText(), /历史手填 7 只/);
    await page.locator('[data-edit-turtle-pool="pool"]').click();
    assert.equal(await page.locator('#turtlePoolForm [name="count"]').inputValue(), '');
    await page.locator('#turtlePoolForm [name="note"]').fill('先改备注，不猜总数');
    await page.locator('#turtlePoolForm').evaluate(form => form.requestSubmit());
    assert.equal(await page.evaluate(() => state.turtlePools[0].count), 7);
    assert.equal(await page.evaluate(() => TurtleBatches.poolCountNeedsReview(state.turtlePools[0])), true);
    await page.locator('[data-edit-turtle-pool="pool"]').click();
    await page.locator('#turtlePoolForm [name="count"]').fill('517');
    await page.locator('#turtlePoolForm').evaluate(form => form.requestSubmit());
    assert.equal(await page.evaluate(() => TurtleBatches.poolCount(state.turtlePools[0], state.turtles)), 517);
    assert.equal(await page.evaluate(() => state.turtlePools[0].legacyCount), 7);
    assert.equal(await page.evaluate(() => state.turtlePools[0].countMode), 'additional');
    await page.reload({ waitUntil: 'load' });
    assert.equal(await page.evaluate(() => TurtleBatches.poolCount(state.turtlePools[0], state.turtles)), 517);
    assert.equal(await page.evaluate(() => state.ledgerRecords.filter(r => r.type === 'purchase').length), 1);
    assert.deepEqual(errors, []);
    console.log('Upgrade UI passed: 500-member purchase stays collapsed, exact cost, historical-count linking, continued hatching, dates and reload without duplicates.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
