'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const bash = process.platform === 'win32' ? 'C:/Program Files/Git/bin/bash.exe' : 'bash';
const script = 'scripts/copy-community-recommendation-server-command.sh';
execFileSync(bash, ['-n', script], { cwd: root });
const command = execFileSync(bash, ['-l', script, '--print'], { cwd: root, maxBuffer: 100000, stdio: ['ignore', 'pipe', 'pipe'] });
execFileSync(bash, ['-n'], { input: command });
const source = command.toString('utf8');
const encoded = source.match(/<<'TURTLE_PATCH_BASE64'\r?\n([\s\S]*?)\r?\nTURTLE_PATCH_BASE64\r?\n/);
assert.ok(encoded, 'Complete payload heredoc must exist');
assert.match(encoded[1].trim(), /^[A-Za-z0-9+/=\r\n]+$/);
const bytes = Buffer.from(encoded[1].replace(/\s+/g, ''), 'base64');
assert.ok(bytes.equals(fs.readFileSync(path.join(root, 'deploy/patches/turtlekeeper-community-recommendation-v3.tar.gz'))));
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), '6bd6fb390053e0ddbba11f4a474400e24ed0644f995d1701a770bc81b72ad358');
assert.ok(command.length < 12000, 'Keep clipboard transport below 12 KB');
assert.ok(source.includes('node deploy-community-recommendation.cjs --check\nnode deploy-community-recommendation.cjs --apply'));
assert.ok(!source.includes('curl ') && !source.includes('scp '));
fs.writeFileSync(path.join(root, 'output/install-community-recommendation-v3.sh'), command);
console.log(`PASS: Git Bash generator and server syntax; exact ${bytes.length}-byte patch round trip; ${command.length}-byte command. No clipboard write or server execution in this test.`);
