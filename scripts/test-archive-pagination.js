const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const TurtleBatches = require('../assets/turtle-batches');
const source = fs.readFileSync(require('node:path').join(__dirname, '../app.js'), 'utf8');
const ctx = { state: { turtles: [], loggedInPhone: 'test', turtleFilter: 'all', turtlePoolFilter: 'all', turtleSort: 'default' }, TurtleBatches, toast() {} };
ctx.setState = patch => Object.assign(ctx.state, patch);
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('const ARCHIVE_PAGE_SIZE ='), source.indexOf('function sortedTurtles()')), ctx);
vm.runInContext(source.slice(source.indexOf('function persistDashboardTurtleOrder('), source.indexOf('function setupDashboardTurtleReorder(')), ctx);
const turtles = Array.from({ length: 850 }, (_, i) => ({ id: String(i), code: `GHG-${i + 1}`, speciesName: '果核蛋龟' }));
assert.equal(ctx.archivePageData(turtles).rows.length, 30);
const seen = [];
for (let page = 0; page < 29; page++) {
  vm.runInContext(`archiveListView.page = ${page}`, ctx);
  const data = ctx.archivePageData(turtles);
  assert.equal(data.pages, 29);
  assert.ok(data.rows.length <= 30);
  seen.push(...data.rows.map(t => t.id));
}
assert.deepEqual(seen, turtles.map(t => t.id), 'Every archive is reachable, exactly once');
ctx.state.turtlePoolFilter = 'new';
assert.equal(ctx.archivePageData(turtles).start, 0, 'Changing filters resets pagination');
vm.runInContext('archiveListView.query = "GHG-850"', ctx);
assert.equal(ctx.archivePageData(turtles).rows[0].id, '849', 'Search covers unloaded archives');
vm.runInContext('archiveListView.query = "missing"', ctx);
assert.equal(ctx.archivePageData(turtles).total, 0);
vm.runInContext('archiveListView.query = ""', ctx);
ctx.archivePageData(turtles);
vm.runInContext('archiveListView.page = 28', ctx);
assert.equal(ctx.archivePageData(turtles.slice(0, 40)).start, 30, 'Clamp after deletion');
const grouped = turtles.map((t, i) => i < 500 ? { ...t, batchId: 'batch' } : t);
ctx.state.turtles = grouped;
const before = JSON.stringify(grouped);
ctx.persistDashboardTurtleOrder({ querySelectorAll: () => ['500', '0', '501'].map(id => ({ dataset: { reorderTurtle: id } })) });
assert.equal(ctx.state.turtles.length, 850, 'Reordering does not collapse underlying batch inventory');
assert.equal(new Set(ctx.state.turtles.map(t => t.id)).size, 850);
assert.equal(ctx.state.turtles[0].id, '500');
assert.equal(ctx.state.turtles[1].id, '0');
assert.equal(ctx.state.turtles.filter(t => t.batchId === 'batch').length, 500);
assert.ok(ctx.state.turtles.every(t => !t.batchMembers), 'Never persist view-only grouped objects');
assert.equal(JSON.stringify(grouped), before, 'Do not mutate existing inventory');
console.log('850 archives: 29 bounded pages, global search, filter reset, deletion clamp and batch reorder passed.');
